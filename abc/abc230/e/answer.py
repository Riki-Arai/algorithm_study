'''
(1) 指示通りに計算をすると処理が間に合わないので計算で答えを導出したい
(2) 例えなNの1/2より大きい数のiの時は全て1となるので、この区間はまとめて計算できそう
    →全て1、2、3の区間は意外と大きそうなので区間ごとに計算をすれば間に合うのでは？
(3) i=1から始めて切り捨ての数が同じ区間を特定して計算
※解説を読んだ後の感想
(4) 結果的にはACできたが計算量の見積もりを正しくできたとは言い難い印象
(5) ルートNを境界として場合わけして考えてみると、切り捨ての値は高々で2*ルートN種類数しかないと判断できる
(6) なので切り捨ての値を求める*区間といった形で計算が間に合うと判断ができる
(5) Nの数がでかい時はルートを考えてみると良さそう 
'''
N = int(input())

res = 0
i = 1
while i <= N:
    k = N // i
    next_i = N // k + 1
    res += k * (next_i - i)
    i = next_i

print(res)